/**
 * Lightweight deception layer.
 *
 * Detects known-sensitive path probes (honeytoken/bait routes) and hostile
 * scanner user agents, answers them with inert decoys, and (when configured)
 * posts a signed alert to an ops webhook. Designed to be fail-open: every
 * function catches its own errors and the caller must never depend on it for
 * correctness. Real application paths and API endpoints are never intercepted.
 */

